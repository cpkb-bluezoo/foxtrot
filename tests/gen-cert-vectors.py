#!/usr/bin/env python3
# Generate tests/vectors-cert.h: OpenSSH certificates made by ssh-keygen -s
# (an implementation that shares no code with src/cert.c), and signatures by
# the certified keys made by the python "cryptography" package.
#
# Usage: python3 gen-cert-vectors.py > vectors-cert.h
import base64, os, struct, subprocess, tempfile

# ssh-keygen -V reads local time; the vectors must not depend on it.
os.environ['TZ'] = 'UTC'
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, padding, rsa, utils

MSG = b'foxtrot certificate test message'

def s(b): return struct.pack('>I', len(b)) + b
def mpint(n):
    b = n.to_bytes((n.bit_length() + 7) // 8, 'big')
    if b and b[0] & 0x80: b = b'\0' + b
    return s(b)

def emit(name, data):
    if isinstance(data, bytes): data = data.hex()
    print('static const char *const %s =' % name)
    for i in range(0, max(len(data), 1), 100):
        print('  "%s"%s' % (data[i:i+100], ';' if i + 100 >= len(data) else ''))

def text(name, t):
    lines = t.splitlines(keepends=True)
    print('static const char %s[] =' % name)
    for i, l in enumerate(lines):
        print('  "%s\\n"%s' % (l.rstrip('\n'), ';' if i == len(lines) - 1 else ''))

d = tempfile.mkdtemp()
def keygen(name, kind, args=()):
    f = os.path.join(d, name)
    subprocess.check_call(['ssh-keygen', '-q', '-t', kind, '-N', '', '-C', name, '-f', f] + list(args))
    return f

def sign(ca, subject, ident, principals, extra, host=False, serial=1):
    cmd = ['ssh-keygen', '-q', '-s', ca, '-I', ident, '-z', str(serial), '-n', principals] + extra
    if host: cmd.append('-h')
    subprocess.check_call(cmd + [subject + '.pub'])
    line = open(subject + '-cert.pub').read().split()
    return base64.b64decode(line[1])

def fp(path):
    return subprocess.check_output(['ssh-keygen', '-l', '-f', path]).decode().split()[1]

print('/* Generated by gen-cert-vectors.py; do not edit.  Throwaway test keys.  */')
print()
emit('vec_msg', MSG)

cas = {'ed': keygen('ca_ed', 'ed25519'),
       'p256': keygen('ca_p256', 'ecdsa', ['-b', '256']),
       'rsa': keygen('ca_rsa', 'rsa', ['-b', '2048'])}
for k, f in cas.items():
    pub = base64.b64decode(open(f + '.pub').read().split()[1])
    emit('vec_ca_%s_blob' % k, pub)
    text('vec_ca_%s_private' % k, open(f).read())

subjects = {'ed': ('ed25519', []), 'p256': ('ecdsa', ['-b', '256']),
            'p384': ('ecdsa', ['-b', '384']), 'rsa': ('rsa', ['-b', '2048'])}
for tag, (kind, args) in subjects.items():
    f = keygen('subj_' + tag, kind, args)
    key = serialization.load_ssh_private_key(open(f).read().encode(), None)
    text('vec_%s_private' % tag, open(f).read())
    ca = cas['ed' if tag != 'rsa' else 'rsa']
    # A user certificate, good until 2099, with principals and an option.
    ublob = sign(ca, f, 'user-%s' % tag, 'alice,bob',
                 ['-V', '20200101:20991231', '-O', 'force-command=/bin/true',
                  '-O', 'source-address=192.0.2.0/24'], serial=1000 + len(tag))
    emit('vec_%s_user_cert' % tag, ublob)
    print('static const char vec_%s_user_fp[] = "%s";' % (tag, fp(f + '-cert.pub')))
    # A host certificate with a wildcard principal.
    hblob = sign(ca, f, 'host-%s' % tag, '*.example.org,example.com',
                 ['-V', '20200101:20991231'], host=True, serial=77)
    emit('vec_%s_host_cert' % tag, hblob)
    # Independent signatures by the certified key; the certificate algorithm
    # signs in the format of the plain one.
    if tag == 'ed':
        emit('vec_ed_sig', s(b'ssh-ed25519') + s(key.sign(MSG)))
    elif tag in ('p256', 'p384'):
        h = hashes.SHA256() if tag == 'p256' else hashes.SHA384()
        r, sv = utils.decode_dss_signature(key.sign(MSG, ec.ECDSA(h)))
        emit('vec_%s_sig' % tag, s(b'ecdsa-sha2-nistp%s' % tag[1:].encode()) + s(mpint(r) + mpint(sv)))
    else:
        emit('vec_rsa_sig256', s(b'rsa-sha2-256') + s(key.sign(MSG, padding.PKCS1v15(), hashes.SHA256())))
        emit('vec_rsa_sig512', s(b'rsa-sha2-512') + s(key.sign(MSG, padding.PKCS1v15(), hashes.SHA512())))

# Validity windows, no validity limits at all, an unknown critical option,
# a certificate from an ECDSA CA, and one from an RSA CA that signed with
# SHA-1 (which the policy refuses).
f = os.path.join(d, 'subj_ed')
emit('vec_expired_cert', sign(cas['ed'], f, 'old', 'alice', ['-V', '20100101:20110101']))
emit('vec_future_cert', sign(cas['ed'], f, 'future', 'alice', ['-V', '20990101:20991231']))
emit('vec_unknown_critical_cert', sign(cas['ed'], f, 'crit', 'alice', ['-V', '20200101:20991231', '-O', 'critical:foo@example.org=bar']))
emit('vec_verify_cert', sign(cas['ed'], f, 'verify', 'alice', ['-O', 'verify-required']))
emit('vec_forever_cert', sign(cas['ed'], f, 'forever', 'alice', [], serial=9))
emit('vec_p256ca_cert', sign(cas['p256'], f, 'p256-signed', 'alice', ['-V', '20200101:20991231']))
sha1 = keygen('ca_rsa_sha1', 'rsa', ['-b', '2048'])
emit('vec_sha1_ca_cert', sign(sha1, f, 'sha1', 'alice', ['-V', '20200101:20991231', '-t', 'ssh-rsa']))
