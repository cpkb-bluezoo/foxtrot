#!/usr/bin/env python3
# Generate tests/vectors-keyfmt.h: one key of each type written in the other
# formats by tools that share no code with src/keyfmt.c: python's
# cryptography package (PKCS#8, PKCS#1, SEC1, SPKI, the OpenSSH public key),
# openssl (PKCS#8 under PBES2 with other ciphers and hashes, the old PEM
# encryption, scrypt), ssh-keygen (RFC 4716 and the randomart of -lv) and
# puttygen (PuTTY files of formats 2 and 3, with each Argon2).  The expected
# public key is python's.
#
# Usage: PUTTYGEN=/path/to/puttygen python3 gen-keyfmt-vectors.py > vectors-keyfmt.h
import os, subprocess, tempfile
from cryptography.hazmat.primitives import serialization as S
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, rsa

os.environ['TZ'] = 'UTC'
PUTTYGEN = os.environ.get('PUTTYGEN', 'puttygen')
PASS = 'correct horse'
d = tempfile.mkdtemp()

def cstr(name, text, static='static const char'):
    lines = text.splitlines(keepends=True) or ['']
    print('%s %s[] =' % (static, name))
    for i, l in enumerate(lines):
        print('  "%s"%s' % (l.rstrip('\n').replace('\\', '\\\\').replace('"', '\\"') + ('\\n' if l.endswith('\n') else ''),
                          ';' if i == len(lines) - 1 else ''))

def run(*a, check=True, inp=None):
    return subprocess.run(list(a), cwd=d, capture_output=True, text=True, check=check, input=inp)

def write(name, data):
    p = os.path.join(d, name)
    open(p, 'w' if isinstance(data, str) else 'wb').write(data)
    return name

keys = [
    ('ed25519', ed25519.Ed25519PrivateKey.generate()),
    ('p256', ec.generate_private_key(ec.SECP256R1())),
    ('p384', ec.generate_private_key(ec.SECP384R1())),
    ('rsa', rsa.generate_private_key(65537, 2048)),
]
print('/* Generated by gen-keyfmt-vectors.py; do not edit.  Throwaway test keys.  */')
print()
print('#define VEC_PASS "%s"' % PASS)
print()

rows = []
encs = []
ppk_encs = []
for kind, key in keys:
    pub = key.public_key()
    P = S.Encoding.PEM
    ossh = key.private_bytes(S.Encoding.PEM, S.PrivateFormat.OpenSSH, S.NoEncryption()).decode()
    pubtext = pub.public_bytes(S.Encoding.OpenSSH, S.PublicFormat.OpenSSH).decode()
    pkcs8 = key.private_bytes(P, S.PrivateFormat.PKCS8, S.NoEncryption()).decode()
    spki = pub.public_bytes(P, S.PublicFormat.SubjectPublicKeyInfo).decode()
    sec1 = pkcs1 = rsapub = ''
    if kind == 'rsa':
        pkcs1 = key.private_bytes(P, S.PrivateFormat.TraditionalOpenSSL, S.NoEncryption()).decode()
        rsapub = pub.public_bytes(P, S.PublicFormat.PKCS1).decode()
    elif kind != 'ed25519':
        sec1 = key.private_bytes(P, S.PrivateFormat.TraditionalOpenSSL, S.NoEncryption()).decode()
    # ssh-keygen and puttygen read the OpenSSH private key file; a comment
    # makes the RFC 4716 and PuTTY files carry one.
    write('k_' + kind, ossh); os.chmod(os.path.join(d, 'k_' + kind), 0o600)
    write('k_%s.pub' % kind, pubtext + ' test comment\n')
    rfc = run('ssh-keygen', '-e', '-m', 'RFC4716', '-f', 'k_%s.pub' % kind).stdout
    art = run('ssh-keygen', '-lv', '-f', 'k_%s.pub' % kind).stdout
    art = '\n'.join(art.splitlines()[1:]) + '\n'
    ppk = run(PUTTYGEN, 'k_' + kind, '-o', 'k.ppk', '-O', 'private', '-C', 'test comment', '--ppk-param', 'version=3') and open(os.path.join(d, 'k.ppk')).read()
    rows.append(kind)
    cstr('vec_fmt_%s_pub' % kind, pubtext)
    cstr('vec_fmt_%s_ossh' % kind, ossh)
    cstr('vec_fmt_%s_pkcs8' % kind, pkcs8)
    cstr('vec_fmt_%s_spki' % kind, spki)
    cstr('vec_fmt_%s_sec1' % kind, sec1)
    cstr('vec_fmt_%s_pkcs1' % kind, pkcs1)
    cstr('vec_fmt_%s_rsapub' % kind, rsapub)
    cstr('vec_fmt_%s_rfc4716' % kind, rfc)
    cstr('vec_fmt_%s_art' % kind, art)
    cstr('vec_fmt_%s_ppk' % kind, ppk)
    # The encrypted forms, from the PKCS#8.
    write('pk8_%s.pem' % kind, pkcs8)
    for cipher in ('aes-128-cbc', 'aes-192-cbc', 'aes-256-cbc'):
        for prf in ('hmacWithSHA256', 'hmacWithSHA384', 'hmacWithSHA512'):
            if (cipher, prf) not in (('aes-256-cbc', 'hmacWithSHA256'), ('aes-128-cbc', 'hmacWithSHA512'),
                                      ('aes-192-cbc', 'hmacWithSHA384')) and kind != 'ed25519':
                continue
            out = run('openssl', 'pkcs8', '-topk8', '-in', 'pk8_%s.pem' % kind, '-v2', cipher, '-v2prf', prf,
                      '-passout', 'pass:' + PASS, '-iter', '2000').stdout
            nm = 'vec_fmt_%s_enc_%s_%s' % (kind, cipher.replace('-', '_'), prf)
            cstr(nm, out)
            encs.append((kind, '%s %s' % (cipher, prf), nm))
    for kdf in ('argon2id', 'argon2i', 'argon2d'):
        if kdf != 'argon2id' and kind not in ('ed25519', 'rsa'):
            continue
        write('pw', PASS + '\n')
        run(PUTTYGEN, 'k_' + kind, '-o', 'e.ppk', '-O', 'private', '-C', 'test comment', '--new-passphrase', 'pw',
            '--ppk-param', 'version=3,kdf=%s,memory=1024,passes=2,parallelism=1' % kdf)
        nm = 'vec_fmt_%s_ppk_%s' % (kind, kdf)
        cstr(nm, open(os.path.join(d, 'e.ppk')).read())
        ppk_encs.append((kind, kdf, nm))

# A picture in which a cell was visited often enough to need the cap, found
# by trying keys.
tries = 0
while True:
    tries += 1
    run('ssh-keygen', '-q', '-t', 'ed25519', '-N', '', '-f', 'hot', '-C', 'hot') if not os.path.exists(os.path.join(d, 'hot')) else None
    art = run('ssh-keygen', '-lv', '-f', 'hot.pub').stdout
    if '^' in art or tries > 400:
        break
    os.remove(os.path.join(d, 'hot')); os.remove(os.path.join(d, 'hot.pub'))
hot_pub = ' '.join(open(os.path.join(d, 'hot.pub')).read().split()[:2]) + '\n'
cstr('vec_fmt_hot_pub', hot_pub)
cstr('vec_fmt_hot_art', '\n'.join(art.splitlines()[1:]) + '\n')
cstr('vec_fmt_hot_has', '^' if '^' in art else 'no')

# Files that must be refused.
rsa_key = keys[3][1]
write('rsa.pem', rsa_key.private_bytes(S.Encoding.PEM, S.PrivateFormat.TraditionalOpenSSL, S.NoEncryption()))
write('pk8_rsa.pem', rsa_key.private_bytes(S.Encoding.PEM, S.PrivateFormat.PKCS8, S.NoEncryption()))
refused = []
def refuse(name, text, expect):
    cstr('vec_fmt_bad_' + name, text)
    refused.append((name, expect))
refuse('old_pem_encryption', run('openssl', 'rsa', '-in', 'rsa.pem', '-aes128', '-traditional', '-passout', 'pass:' + PASS).stdout, 'GF_ERR_UNSUPPORTED')
refuse('pbkdf2_sha1', run('openssl', 'pkcs8', '-topk8', '-in', 'pk8_rsa.pem', '-v2', 'aes-256-cbc', '-v2prf', 'hmacWithSHA1', '-passout', 'pass:' + PASS).stdout, 'GF_ERR_UNSUPPORTED')
refuse('scrypt', run('openssl', 'pkcs8', '-topk8', '-in', 'pk8_rsa.pem', '-scrypt', '-passout', 'pass:' + PASS).stdout, 'GF_ERR_UNSUPPORTED')
r = run('openssl', 'pkcs8', '-topk8', '-in', 'pk8_rsa.pem', '-v1', 'PBE-SHA1-3DES', '-passout', 'pass:' + PASS, '-provider', 'default', '-provider', 'legacy', check=False)
if r.returncode == 0 and r.stdout:
    refuse('pbes1', r.stdout, 'GF_ERR_UNSUPPORTED')
run('openssl', 'ecparam', '-name', 'secp521r1', '-genkey', '-noout', '-out', 'p521.pem')
refuse('p521', open(os.path.join(d, 'p521.pem')).read(), 'GF_ERR_UNSUPPORTED')
run('openssl', 'genpkey', '-algorithm', 'RSA', '-pkeyopt', 'rsa_keygen_bits:1024', '-out', 'small.pem')
refuse('rsa1024', open(os.path.join(d, 'small.pem')).read(), 'ANY')
run('openssl', 'dsaparam', '-genkey', '-out', 'dsa.pem', '1024', check=False)
if os.path.exists(os.path.join(d, 'dsa.pem')):
    refuse('dsa', open(os.path.join(d, 'dsa.pem')).read(), 'ANY')
run(PUTTYGEN, 'k_ed25519', '-o', 'v2.ppk', '-O', 'private', '--ppk-param', 'version=2')
refuse('ppk_v2', open(os.path.join(d, 'v2.ppk')).read(), 'GF_ERR_UNSUPPORTED')
run(PUTTYGEN, 'k_ed25519', '-o', 'v2e.ppk', '-O', 'private', '--new-passphrase', 'pw', '--ppk-param', 'version=2')
refuse('ppk_v2_encrypted', open(os.path.join(d, 'v2e.ppk')).read(), 'GF_ERR_UNSUPPORTED')

print()
print('struct vec_fmt_key')
print('{')
print('  const char *kind, *pub, *ossh, *pkcs8, *spki, *sec1, *pkcs1, *rsapub, *rfc4716, *art, *ppk;')
print('};')
print('static const struct vec_fmt_key vec_fmt_keys[] = {')
for k in rows:
    print('  { "%s", %s },' % (k, ', '.join('vec_fmt_%s_%s' % (k, f) for f in
          ('pub', 'ossh', 'pkcs8', 'spki', 'sec1', 'pkcs1', 'rsapub', 'rfc4716', 'art', 'ppk'))))
print('};')
print()
print('struct vec_fmt_enc')
print('{')
print('  const char *kind, *what, *text;')
print('};')
print('static const struct vec_fmt_enc vec_fmt_encs[] = {')
for kind, what, nm in encs:
    print('  { "%s", "%s", %s },' % (kind, what, nm))
print('};')
print('static const struct vec_fmt_enc vec_fmt_ppk_encs[] = {')
for kind, what, nm in ppk_encs:
    print('  { "%s", "%s", %s },' % (kind, what, nm))
print('};')
print()
print('struct vec_fmt_bad')
print('{')
print('  const char *name, *text;')
print('  int expect;			/* A status, or 1 for any failure.  */')
print('};')
print('#define ANY 1')
print('static const struct vec_fmt_bad vec_fmt_bads[] = {')
for name, expect in refused:
    print('  { "%s", vec_fmt_bad_%s, %s },' % (name, name, expect))
print('};')
