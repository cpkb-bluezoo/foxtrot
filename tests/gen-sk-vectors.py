#!/usr/bin/env python3
# Generate tests/vectors-sk.h: FIDO security keys (PROTOCOL.u2f) and
# signatures as a token makes them, written from the format description with
# the python "cryptography" package, and certificates for such keys made by
# ssh-keygen -s.  The layout is checked here against OpenSSH itself: the same
# kind of signature, wrapped as an sshsig file, must be accepted by
# ssh-keygen -Y check-novalidate, and refused with a flag changed.
#
# Usage: python3 gen-sk-vectors.py > vectors-sk.h
import base64, hashlib, os, struct, subprocess, tempfile
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, utils

os.environ['TZ'] = 'UTC'
MSG = b'foxtrot security key test message'

def s(b): return struct.pack('>I', len(b)) + b
def mpint(n):
    b = n.to_bytes((n.bit_length() + 7) // 8, 'big')
    if b and b[0] & 0x80: b = b'\0' + b
    return s(b)

def emit(name, data):
    if isinstance(data, bytes):
        data = data.hex()
    print('static const char *const %s =' % name)
    for i in range(0, len(data), 100):
        print('  "%s"%s' % (data[i:i+100], ';' if i + 100 >= len(data) else ''))

def text(name, t):
    print('static const char %s[] = "%s";' % (name, t.strip()))

d = tempfile.mkdtemp()

class SK:
    def __init__(self, kind, app):
        self.kind, self.app = kind, app
        if kind == 'ed':
            self.key = ed25519.Ed25519PrivateKey.generate()
            self.name = b'sk-ssh-ed25519@openssh.com'
            pk = self.key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
            self.blob = s(self.name) + s(pk) + s(app)
        else:
            self.key = ec.generate_private_key(ec.SECP256R1())
            self.name = b'sk-ecdsa-sha2-nistp256@openssh.com'
            q = self.key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
            self.blob = s(self.name) + s(b'nistp256') + s(q) + s(app)

    def sign(self, msg, flags, counter):
        data = hashlib.sha256(self.app).digest() + bytes([flags]) + struct.pack('>I', counter) + hashlib.sha256(msg).digest()
        if self.kind == 'ed':
            sig = self.key.sign(data)
            body = s(sig)
        else:
            r, sv = utils.decode_dss_signature(self.key.sign(data, ec.ECDSA(hashes.SHA256())))
            body = s(mpint(r) + mpint(sv))
        return s(self.name) + body + bytes([flags]) + struct.pack('>I', counter)

    def publine(self):
        return self.name.decode() + ' ' + base64.b64encode(self.blob).decode()

def sshsig_check(sk, flags, good):
    """Wrap a signature as an sshsig file and ask ssh-keygen about it."""
    ns = b'foxtrot'
    msg = b'message for sshsig'
    h = hashlib.sha512(msg).digest()
    signed = b'SSHSIG' + s(ns) + s(b'') + s(b'sha512') + s(h)
    sig = sk.sign(signed, flags, 99)
    blob = b'SSHSIG' + struct.pack('>I', 1) + s(sk.blob) + s(ns) + s(b'') + s(b'sha512') + s(sig)
    b64 = base64.b64encode(blob).decode()
    armored = '-----BEGIN SSH SIGNATURE-----\n' + '\n'.join(b64[i:i+70] for i in range(0, len(b64), 70)) + '\n-----END SSH SIGNATURE-----\n'
    sf = os.path.join(d, 'sig')
    open(sf, 'w').write(armored)
    r = subprocess.run(['ssh-keygen', '-Y', 'check-novalidate', '-n', 'foxtrot', '-s', sf],
                       input=msg, capture_output=True)
    return r.returncode == 0, (r.stdout + r.stderr).decode()

print('/* Generated by gen-sk-vectors.py; do not edit.  Throwaway keys.  */')
print()
emit('vec_msg', MSG)

keys = {'ed': SK('ed', b'ssh:'), 'p256': SK('p256', b'ssh:')}
other_app = SK('ed', b'ssh:foxtrot')
for tag, k in list(keys.items()) + [('ed_app', other_app)]:
    emit('vec_sk_%s_blob' % tag, k.blob)
    text('vec_sk_%s_pub' % tag, k.publine())
    emit('vec_sk_%s_sig_up' % tag, k.sign(MSG, 0x01, 0x12345678))
    emit('vec_sk_%s_sig_upuv' % tag, k.sign(MSG, 0x05, 7))
    emit('vec_sk_%s_sig_nouv' % tag, k.sign(MSG, 0x01, 0))
    emit('vec_sk_%s_sig_noup' % tag, k.sign(MSG, 0x00, 5))
    emit('vec_sk_%s_sig_other' % tag, k.sign(b'another message', 0x01, 5))

# OpenSSH reads the same layout: a good one is accepted, the same with the
# flags byte changed after signing is not.
for tag, k in keys.items():
    ok, out = sshsig_check(k, 0x01, True)
    if not ok:
        raise SystemExit('ssh-keygen does not accept our %s signature: %s' % (tag, out))

# Certificates for security keys, from ssh-keygen.
ca = os.path.join(d, 'ca')
subprocess.check_call(['ssh-keygen', '-q', '-t', 'ed25519', '-N', '', '-C', '', '-f', ca])
emit('vec_sk_ca_blob', base64.b64decode(open(ca + '.pub').read().split()[1]))
def certify(tag, k, extra=()):
    f = os.path.join(d, 'sk_' + tag)
    open(f + '.pub', 'w').write(k.publine() + '\n')
    subprocess.check_call(['ssh-keygen', '-q', '-s', ca, '-I', 'sk-' + tag, '-n', 'alice'] + list(extra) + [f + '.pub'])
    return base64.b64decode(open(f + '-cert.pub').read().split()[1])
emit('vec_sk_ed_cert', certify('ed', keys['ed'], ['-V', '20200101:20991231']))
emit('vec_sk_p256_cert', certify('p256', keys['p256'], ['-V', '20200101:20991231']))
emit('vec_sk_ed_cert_uv', certify('ed2', keys['ed'], ['-V', '20200101:20991231', '-O', 'verify-required']))
