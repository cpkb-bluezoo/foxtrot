#!/usr/bin/env python3
# Generate tests/vectors-packet.h: known-answer vectors for the SSH binary
# packet protocol, computed with the python "cryptography" package (OpenSSL),
# independently of libgcrypt and of src/packet.c.
#
#   chacha20-poly1305@openssh.com: OpenSSH PROTOCOL.chacha20poly1305
#   aes128-gcm@openssh.com, aes256-gcm@openssh.com: RFC 5647 section 7.1
#
# Usage: python3 gen-packet-vectors.py > vectors-packet.h
import struct
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives import poly1305

def chacha(key, seq, counter, data):
    # DJB ChaCha20: 64-bit block counter, 64-bit nonce (the sequence number
    # as a big-endian integer); OpenSSL takes counter || nonce as its IV.
    iv = struct.pack('<Q', counter) + struct.pack('>Q', seq)
    c = Cipher(algorithms.ChaCha20(key, iv), mode=None).encryptor()
    return c.update(data) + c.finalize()

def build(payload, padding):
    pl = 1 + len(payload) + len(padding)
    return pl, bytes([len(padding)]) + payload + padding

def seal_none(payload, padding):
    pl, body = build(payload, padding)
    return struct.pack('>I', pl) + body

def seal_chacha(key, seq, payload, padding):
    k2, k1 = key[:32], key[32:]
    pl, body = build(payload, padding)
    polykey = chacha(k2, seq, 0, bytes(32))
    enc_len = chacha(k1, seq, 0, struct.pack('>I', pl))
    enc_body = chacha(k2, seq, 1, body)
    tag = poly1305.Poly1305.generate_tag(polykey, enc_len + enc_body)
    return enc_len + enc_body + tag

def seal_gcm(key, iv, payload, padding):
    pl, body = build(payload, padding)
    aad = struct.pack('>I', pl)
    return aad + AESGCM(key).encrypt(iv, body, aad)

def hexs(b): return b.hex()

def inc_iv(iv):
    ctr = (int.from_bytes(iv[4:], 'big') + 1) % (1 << 64)
    return iv[:4] + ctr.to_bytes(8, 'big')

def emit(name, v):
    print('static const char *const %s = "%s";' % (name, v))

key64 = bytes(range(0x40, 0x80))
key32 = bytes(range(0x20, 0x40))
key16 = bytes(range(0x10, 0x20))
iv = bytes.fromhex('a0a1a2a3' + '00000000fffffffe')   # counter about to carry
payload1 = bytes([0x05]) + b'\x00\x00\x00\x0cssh-userauth'          # SERVICE_REQUEST
payload2 = bytes([0x02]) + bytes(range(100, 130))                   # IGNORE
pad_none1 = bytes([0xaa]) * 7      # 4 + 1 + len(payload1)=17 + 7 -> 29? checked below
print('/* Generated by gen-packet-vectors.py; do not edit.  */')
print()
emit('vec_payload1', hexs(payload1))
emit('vec_payload2', hexs(payload2))
emit('vec_key64', hexs(key64))
emit('vec_key32', hexs(key32))
emit('vec_key16', hexs(key16))
emit('vec_iv', hexs(iv))

def pad_for(bs, payload, aad):
    n = (aad + 1 + len(payload))
    p = bs - n % bs
    if p < 4: p += bs
    return bytes([0x55 + i for i in range(p)])

emit('vec_none1', hexs(seal_none(payload1, pad_for(8, payload1, 4))))
emit('vec_none1_pad', hexs(pad_for(8, payload1, 4)))
for seq in (0, 7):
    emit('vec_chacha_seq%d_1' % seq,
         hexs(seal_chacha(key64, seq, payload1, pad_for(8, payload1, 0))))
    emit('vec_chacha_seq%d_pad1' % seq, hexs(pad_for(8, payload1, 0)))
emit('vec_chacha_seq7_2',
     hexs(seal_chacha(key64, 8, payload2, pad_for(8, payload2, 0))))
emit('vec_chacha_seq7_pad2', hexs(pad_for(8, payload2, 0)))
for bits, key in ((128, key16), (256, key32)):
    i1 = iv
    i2 = inc_iv(i1)
    i3 = inc_iv(i2)
    emit('vec_gcm%d_1' % bits, hexs(seal_gcm(key, i1, payload1, pad_for(16, payload1, 0))))
    emit('vec_gcm%d_2' % bits, hexs(seal_gcm(key, i2, payload2, pad_for(16, payload2, 0))))
    emit('vec_gcm%d_3' % bits, hexs(seal_gcm(key, i3, payload1, pad_for(16, payload1, 0))))
emit('vec_pad16_1', hexs(pad_for(16, payload1, 0)))
emit('vec_pad16_2', hexs(pad_for(16, payload2, 0)))
