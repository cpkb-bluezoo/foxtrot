#!/usr/bin/env python3
# Generate tests/vectors-krl.h: key revocation lists made by OpenSSH's
# ssh-keygen -k (and one written here, for what ssh-keygen cannot make: a
# group for any CA, extensions), the keys and certificates they are asked
# about, and the answer to each from ssh-keygen -Q, which shares no code
# with src/krl.c.
#
# Usage: python3 gen-krl-vectors.py > vectors-krl.h
import base64, os, struct, subprocess, tempfile

os.environ['TZ'] = 'UTC'
d = tempfile.mkdtemp()

def run(*a, check=True):
    return subprocess.run(list(a), cwd=d, capture_output=True, text=True, check=check)

def keygen(name, kind='ed25519', *args):
    run('ssh-keygen', '-q', '-t', kind, '-N', '', '-C', name, '-f', name, *args)
    return name

def blob_of(path):
    return base64.b64decode(open(os.path.join(d, path)).read().split()[1])

def publine(name):
    return ' '.join(open(os.path.join(d, name + '.pub')).read().split()[:2])

def emit(name, b):
    h = b.hex()
    print('static const char *const %s =' % name)
    for i in range(0, len(h), 64):
        print('  "%s"%s' % (h[i:i + 64], ';' if i + 64 >= len(h) else ''))
    if not h:
        print('  "";')

def s(b):
    if isinstance(b, str): b = b.encode()
    return struct.pack('>I', len(b)) + b

counter = [0]
def cert(ca, subject, serial, ident):
    counter[0] += 1
    out = 'c%d' % counter[0]
    # ssh-keygen -s writes SUBJECT-cert.pub; give each its own subject copy.
    run('cp', subject + '.pub', out + '.pub')
    run('ssh-keygen', '-q', '-s', ca, '-I', ident, '-z', str(serial), '-n', 'alice',
        '-V', '20200101:20991231', out + '.pub')
    return out + '-cert.pub'

ca1, ca2, ca3 = keygen('ca1'), keygen('ca2'), keygen('ca3')
u = {n: keygen('u_' + n) for n in ('plain', 'key', 'sha1', 'sha256')}
ur = keygen('u_rsa', 'rsa', '-b', '2048')
up = keygen('u_p256', 'ecdsa', '-b', '256')

# ---- the main list, by ssh-keygen ----
def spec(text):
    open(os.path.join(d, 'spec'), 'w').write(text)

def krl(*args):
    run('ssh-keygen', '-k', '-f', 'main.krl', *args, 'spec')

spec('serial: 5\nserial: 100-200\nserial: 1000\nserial: 1001\nserial: 1003\n'
     'serial: 9000000000-9000000002\nid: revoked-by-id\n'
     'serial: 300-310\nserial: 311-320\n'
     'serial: 18446744073709551600\nserial: 18446744073709551601\nserial: 18446744073709551603\n'
     'serial: 18446744073709551610-18446744073709551615\n')
krl('-s', ca1 + '.pub', '-z', '7')
spec('serial: 5\nid: ca2-id\n')
krl('-u', '-s', ca2 + '.pub')
spec('%s\nsha1: %s\nhash: %s\n%s\n' % (
    publine(u['key']), publine(u['sha1']),
    run('ssh-keygen', '-l', '-f', u['sha256'] + '.pub').stdout.split()[1],
    publine(ca3)))
krl('-u')
main = open(os.path.join(d, 'main.krl'), 'rb').read()

# ---- a list for any CA, with extensions, by hand ----
def lists(kind, items): return bytes([kind]) + s(b''.join(items))
def header(version, comment=b''):
    return b'SSHKRL\n\0' + struct.pack('>IQQQ', 1, version, 1700000000, 0) + s(b'') + s(comment)
def certsec(ca_blob, *subs):
    return bytes([1]) + s(s(ca_blob) + s(b'') + b''.join(bytes([k]) + s(v) for k, v in subs))
ext_ok = s('test@example.org') + b'\0' + s(b'x')
wild = (header(3, b'any ca') + certsec(b'', (0x20, struct.pack('>Q', 77) + struct.pack('>Q', 78)),
        (0x21, struct.pack('>QQ', 500, 600)), (0x23, s('any-id')), (0x39, ext_ok)) +
        bytes([255]) + s(ext_ok))

# ---- the certificates and keys asked about ----
queries = []
def ask(name, path, ctx=None):
    raw = blob_of(path)
    res = {}
    for kn, kf in (('main', 'main.krl'), ('wild', 'wild.krl')):
        out = run('ssh-keygen', '-Q', '-f', kf, path, check=False).stdout
        res[kn] = 1 if 'REVOKED' in out else 0
    queries.append((name, raw, res['main'], res['wild']))

open(os.path.join(d, 'wild.krl'), 'wb').write(wild)
for n in u: ask('plain-' + n, u[n] + '.pub')
ask('rsa', ur + '.pub'); ask('p256', up + '.pub')
ask('ca1', ca1 + '.pub'); ask('ca3', ca3 + '.pub')
S = u['plain']
for ca, cn in ((ca1, 'ca1'), (ca2, 'ca2'), (ca3, 'ca3')):
    for ser in (0, 1, 5, 6, 99, 100, 150, 200, 201, 77, 78, 79, 500, 600, 601,
                1000, 1001, 1002, 1003, 1004, 9000000001, 9000000003,
                299, 300, 310, 311, 320, 321, 18446744073709551599, 18446744073709551600,
                18446744073709551601, 18446744073709551602, 18446744073709551603,
                18446744073709551604, 18446744073709551609, 18446744073709551610,
                18446744073709551615):
        ask('%s-serial-%d' % (cn, ser), cert(ca, S, ser, 'plain-id'))
    for ident in ('revoked-by-id', 'ca2-id', 'any-id', 'revoked-by-id-not'):
        ask('%s-id-%s' % (cn, ident), cert(ca, S, 2, ident))
for n in ('key', 'sha1', 'sha256'):
    ask('cert-of-%s' % n, cert(ca2, u[n], 3, 'x'))
ask('cert-of-rsa', cert(ca1, ur, 4000, 'rsa'))

print('/* Generated by gen-krl-vectors.py; do not edit.  Throwaway test keys.  */')
print()
emit('vec_krl_main', main)
emit('vec_krl_wild', wild)
print('struct vec_krl_query')
print('{')
print('  const char *name;')
print('  const char *blob;		/* A key or a certificate.  */')
print('  int main, wild;		/* ssh-keygen -Q: revoked by that list.  */')
print('};')
print()
for i, (n, raw, m, w) in enumerate(queries):
    emit('vec_krl_q%d' % i, raw)
print('static const struct vec_krl_query vec_krl_queries[] = {')
for i, (n, raw, m, w) in enumerate(queries):
    print('  { "%s", vec_krl_q%d, %d, %d },' % (n, i, m, w))
print('};')
