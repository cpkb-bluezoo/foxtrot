#!/usr/bin/env python3
# Generate tests/vectors-key.h: keys made by ssh-keygen (OpenSSH) and
# signatures made by the python "cryptography" package (OpenSSL), so that
# src/key.c is checked against implementations that share no code with it.
#
# Usage: python3 gen-key-vectors.py > vectors-key.h
import base64, hashlib, os, struct, subprocess, tempfile
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, padding, rsa, utils

MSG = b'foxtrot signature test message'

def s(b): return struct.pack('>I', len(b)) + b
def mpint(n):
    b = n.to_bytes((n.bit_length() + 7) // 8, 'big')
    if b and b[0] & 0x80: b = b'\0' + b
    return s(b)

def emit(name, data):
    if isinstance(data, bytes):
        data = data.hex()
    print('static const char *const %s =' % name)
    for i in range(0, len(data), 100):
        print('  "%s"%s' % (data[i:i+100], ';' if i + 100 >= len(data) else ''))

def text(name, t):
    lines = t.splitlines(keepends=True)
    print('static const char %s[] =' % name)
    for i, l in enumerate(lines):
        print('  "%s\\n"%s' % (l.rstrip('\n'), ';' if i == len(lines) - 1 else ''))

def keygen(kind, args):
    with tempfile.TemporaryDirectory() as d:
        f = os.path.join(d, 'k')
        subprocess.check_call(['ssh-keygen', '-q', '-t', kind, '-N', '', '-C', 'foxtrot-test', '-f', f] + args)
        priv = open(f).read()
        pubtext = open(f + '.pub').read()
        pub = pubtext.split()
        fp = subprocess.check_output(['ssh-keygen', '-l', '-f', f + '.pub']).decode().split()[1]
        return priv, base64.b64decode(pub[1]), fp, pubtext

def sigblob(name, data): return s(name.encode()) + s(data)

print('/* Generated by gen-key-vectors.py; do not edit.  */')
print()
emit('vec_msg', MSG)

for tag, kind, args in (('ed', 'ed25519', []), ('p256', 'ecdsa', ['-b', '256']),
                        ('p384', 'ecdsa', ['-b', '384']), ('rsa', 'rsa', ['-b', '2048'])):
    priv, blob, fp, pubtext = keygen(kind, args)
    key = serialization.load_ssh_private_key(priv.encode(), None)
    text('vec_%s_private' % tag, priv)
    emit('vec_%s_blob' % tag, blob)
    print('static const char vec_%s_pub[] = "%s";' % (tag, pubtext.replace('\n', '\\n')))
    print('static const char vec_%s_fp[] = "%s";' % (tag, fp))
    if tag == 'ed':
        emit('vec_ed_sig', sigblob('ssh-ed25519', key.sign(MSG)))
    elif tag in ('p256', 'p384'):
        h = hashes.SHA256() if tag == 'p256' else hashes.SHA384()
        r, sv = utils.decode_dss_signature(key.sign(MSG, ec.ECDSA(h)))
        emit('vec_%s_sig' % tag, sigblob('ecdsa-sha2-nistp%s' % tag[1:], mpint(r) + mpint(sv)))
    else:
        emit('vec_rsa_sig256', sigblob('rsa-sha2-256', key.sign(MSG, padding.PKCS1v15(), hashes.SHA256())))
        emit('vec_rsa_sig512', sigblob('rsa-sha2-512', key.sign(MSG, padding.PKCS1v15(), hashes.SHA512())))
        emit('vec_rsa_sigsha1', sigblob('ssh-rsa', key.sign(MSG, padding.PKCS1v15(), hashes.SHA1())))
