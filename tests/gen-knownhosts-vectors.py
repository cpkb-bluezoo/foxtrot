#!/usr/bin/env python3
# Generate tests/vectors-knownhosts.h: a known_hosts file and the keys and
# certificates it concerns, all made by OpenSSH's ssh-keygen, and the answer
# to "which of the plain keys does this file give this name" from
# ssh-keygen -F, which shares no code with src/knownhosts.c.
#
# Usage: python3 gen-knownhosts-vectors.py > vectors-knownhosts.h
import os, re, subprocess, tempfile

os.environ['TZ'] = 'UTC'

def cstr(name, text):
    lines = text.splitlines(keepends=True)
    print('static const char %s[] =' % name)
    for i, l in enumerate(lines):
        print('  "%s\\n"%s' % (l.rstrip('\n').replace('\\', '\\\\').replace('"', '\\"'),
                              ';' if i == len(lines) - 1 else ''))

def one(name, text):
    print('static const char %s[] = "%s";' % (name, text.strip()))

d = tempfile.mkdtemp()
def keygen(name, kind, args=()):
    f = os.path.join(d, name)
    subprocess.check_call(['ssh-keygen', '-q', '-t', kind, '-N', '', '-C', '', '-f', f] + list(args))
    return f

def pub(f):
    return ' '.join(open(f + '.pub').read().split()[:2])

e = keygen('e', 'ed25519')
p = keygen('p', 'ecdsa', ['-b', '256'])
r = keygen('r', 'rsa', ['-b', '2048'])
ca = keygen('ca', 'ed25519')
ca2 = keygen('ca2', 'ed25519')
rev = keygen('rev', 'ed25519')
other = keygen('other', 'ed25519')

def cert(f, signer, ident, principals, extra=()):
    subprocess.check_call(['ssh-keygen', '-q', '-s', signer, '-h', '-I', ident, '-n', principals,
                           '-V', '20200101:20991231'] + list(extra) + [f + '.pub'])
    return ' '.join(open(f + '-cert.pub').read().split()[:2])

c_good = cert(e, ca, 'good', 'host.ca.example.net,*.dept.ca.example.net')
c_noname = cert(e, ca, 'noname', 'other.example.org')
c_expired = cert(e, ca, 'expired', 'host.ca.example.net', ['-V', '20100101:20110101'])
c_ca2 = cert(e, ca2, 'ca2', 'host.ca.example.net')
c_rev = cert(rev, ca, 'revkey', 'host.ca.example.net')
c_unrevkey = cert(other, ca, 'other', 'host.ca.example.net')

plain = '''# A comment, then a blank line.

example.org,www.example.org %s
*.corp.example.com,!secret.corp.example.com %s
[bastion.example.org]:2222 %s
@cert-authority *.ca.example.net %s
@revoked * %s
MixedCase.Example.ORG %s
q?.fixed.example.org %s
''' % (pub(e), pub(p), pub(r), pub(ca), pub(rev), pub(r), pub(p))

# Hashed names, made by ssh-keygen -H.
hf = os.path.join(d, 'hashed')
open(hf, 'w').write('hashed.example.org %s\n[hashed2.example.org]:2200 %s\n' % (pub(e), pub(p)))
subprocess.check_call(['ssh-keygen', '-q', '-H', '-f', hf], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
hashed = open(hf).read()

# Lines that are refused.
bad = '''badline
host.bad.example.org ssh-ed25519 !!!notbase64
host.dss.example.org ssh-dss AAAAB3NzaC1kc3MAAAAA
@weird host.weird.example.org %s
@cert-authority
host.empty.example.org
,leading.example.org %s
trailing.example.org, %s
|2|abc|def %s
%s
''' % (pub(e), pub(e), pub(e), pub(e), 'host.cert.example.org ' + c_good)

khfile = plain + hashed + bad
kh = os.path.join(d, 'known_hosts')
open(kh, 'w').write(khfile)

print('/* Generated by gen-knownhosts-vectors.py; do not edit.  Throwaway keys.  */')
print()
cstr('vec_kh_file', khfile)
for n, v in (('e', pub(e)), ('p', pub(p)), ('r', pub(r)), ('ca', pub(ca)), ('ca2', pub(ca2)),
             ('rev', pub(rev)), ('other', pub(other)),
             ('cert_good', c_good), ('cert_noname', c_noname), ('cert_expired', c_expired),
             ('cert_ca2', c_ca2), ('cert_rev', c_rev), ('cert_other', c_unrevkey)):
    one('vec_kh_%s' % n, v)

# What ssh-keygen -F says each name matches: the plain keys on the lines
# that apply to it, among e, p and r.
tags = {pub(e): 'e', pub(p): 'p', pub(r): 'r'}
queries = [('example.org', 22), ('www.example.org', 22), ('EXAMPLE.ORG', 22), ('Www.Example.Org', 22),
           ('example.org', 2222), ('a.corp.example.com', 22), ('secret.corp.example.com', 22),
           ('corp.example.com', 22), ('x.y.corp.example.com', 22),
           ('bastion.example.org', 2222), ('bastion.example.org', 22), ('bastion.example.org', 2223),
           ('mixedcase.example.org', 22), ('MIXEDCASE.EXAMPLE.ORG', 22),
           ('q1.fixed.example.org', 22), ('q.fixed.example.org', 22), ('q12.fixed.example.org', 22),
           ('hashed.example.org', 22), ('hashed.example.org', 2200),
           ('hashed2.example.org', 2200), ('hashed2.example.org', 22), ('unknown.example.net', 22),
           ('host.ca.example.net', 22), ('www.example.org.', 22), ('wwwXexample.org', 22),
           ('host.dss.example.org', 22), ('host.bad.example.org', 22), ('leading.example.org', 22),
           ('trailing.example.org', 22), ('host.cert.example.org', 22)]
print()
print('struct vec_kh_query { const char *host; unsigned port; const char *tags; };')
print('static const struct vec_kh_query vec_kh_queries[] = {')
for host, port in queries:
    name = host if port == 22 else '[%s]:%d' % (host, port)
    out = subprocess.run(['ssh-keygen', '-F', name, '-f', kh], capture_output=True).stdout.decode()
    found = set()
    for line in out.splitlines():
        if line.startswith('#') or not line.strip():
            continue
        f = line.split()
        if f[0].startswith('@'):
            continue
        found.add(tags.get(' '.join(f[-2:]), '?'))
    print('  { "%s", %d, "%s" },' % (host, port, ''.join(sorted(found))))
print('};')
