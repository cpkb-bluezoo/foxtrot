#!/usr/bin/env python3
# Generate tests/vectors-keyfile.h: passphrase-protected OpenSSH private key
# files made by ssh-keygen (each with the cipher in its name), the same keys
# unprotected (ssh-keygen -p), and the output of bcrypt-pbkdf for each file
# from the python "bcrypt" package, which is what the test's KDF callback
# hands back: the library has no bcrypt of its own.
#
# Usage: python3 gen-keyfile-vectors.py > vectors-keyfile.h
import base64, os, struct, subprocess, tempfile
import bcrypt

PASS = 'correct horse'
WRONG = 'wrong horse'
CIPHERS = {'aes128-ctr': (16, 16), 'aes192-ctr': (24, 16), 'aes256-ctr': (32, 16),
           'aes128-gcm@openssh.com': (16, 12), 'aes256-gcm@openssh.com': (32, 12)}
CASES = [('ed_ctr256', 'ed25519', [], 'aes256-ctr', 4),
         ('p256_ctr128', 'ecdsa', ['-b', '256'], 'aes128-ctr', 4),
         ('p384_ctr192', 'ecdsa', ['-b', '384'], 'aes192-ctr', 4),
         ('rsa_gcm256', 'rsa', ['-b', '2048'], 'aes256-gcm@openssh.com', 4),
         ('ed_gcm128', 'ed25519', [], 'aes128-gcm@openssh.com', 4),
         ('ed_default', 'ed25519', [], 'aes256-ctr', 16)]

d = tempfile.mkdtemp()

def text(name, t):
    lines = t.splitlines(keepends=True)
    print('static const char %s[] =' % name)
    for i, l in enumerate(lines):
        print('  "%s\\n"%s' % (l.rstrip('\n'), ';' if i == len(lines) - 1 else ''))

def emit(name, data):
    if isinstance(data, bytes):
        data = data.hex()
    print('static const char *const %s =' % name)
    for i in range(0, len(data), 100):
        print('  "%s"%s' % (data[i:i+100], ';' if i + 100 >= len(data) else ''))

def header(pem):
    body = ''.join(l for l in pem.splitlines() if not l.startswith('-----'))
    raw = base64.b64decode(body)
    assert raw.startswith(b'openssh-key-v1\0')
    p = 15
    def string():
        nonlocal p
        n = struct.unpack('>I', raw[p:p+4])[0]
        v = raw[p+4:p+4+n]
        p += 4 + n
        return v
    cipher, kdf, opts = string().decode(), string().decode(), string()
    salt_len = struct.unpack('>I', opts[:4])[0]
    salt = opts[4:4+salt_len]
    rounds = struct.unpack('>I', opts[4+salt_len:])[0]
    return cipher, kdf, salt, rounds

print('/* Generated by gen-keyfile-vectors.py; do not edit.  Throwaway keys.  */')
print()
kdfs = []
for tag, kind, args, cipher, rounds in CASES:
    f = os.path.join(d, tag)
    subprocess.check_call(['ssh-keygen', '-q', '-t', kind, '-N', PASS, '-Z', cipher, '-a', str(rounds),
                           '-C', '', '-f', f] + args)
    enc = open(f).read()
    pub = base64.b64decode(open(f + '.pub').read().split()[1])
    c, k, salt, r = header(enc)
    assert c == cipher and k == 'bcrypt' and r == rounds, (c, k, r)
    plain_file = f + '.plain'
    open(plain_file, 'w').write(enc)
    os.chmod(plain_file, 0o600)
    subprocess.check_call(['ssh-keygen', '-q', '-p', '-P', PASS, '-N', '', '-f', plain_file],
                          stdout=subprocess.DEVNULL)
    text('vec_kf_%s_enc' % tag, enc)
    text('vec_kf_%s_plain' % tag, open(plain_file).read())
    emit('vec_kf_%s_pub' % tag, pub)
    kl, il = CIPHERS[cipher]
    for p in (PASS, WRONG):
        out = bcrypt.kdf(p.encode(), salt, kl + il, rounds, ignore_few_rounds=True)
        kdfs.append((p, salt, rounds, kl + il, out))
print()
print('struct vec_kf_case { const char *name, *cipher, *enc, *plain, *pub; };')
print('struct vec_kf_kdf { const char *pass; const char *salt; unsigned rounds; unsigned outlen; const char *out; };')
print('static const struct vec_kf_kdf vec_kf_kdfs[] = {')
for p, salt, rounds, n, out in kdfs:
    print('  { "%s", "%s", %d, %d, "%s" },' % (p, salt.hex(), rounds, n, out.hex()))
print('};')
print('static const struct vec_kf_case vec_kf_cases[] = {')
for tag, kind, args, cipher, rounds in CASES:
    print('  { "%s", "%s", vec_kf_%s_enc, vec_kf_%s_plain, vec_kf_%s_pub },' % (tag, cipher, tag, tag, tag))
print('};')
