#!/usr/bin/env python3
# Generate tests/vectors-kex.h: exchange hash and key derivation vectors
# (RFC 4253 sections 7.2 and 8, with K as an mpint or, for the hybrid
# methods, a string), computed with python's hashlib from first principles.
#
# Usage: python3 gen-kex-vectors.py > vectors-kex.h
import hashlib, struct

def s(b): return struct.pack('>I', len(b)) + b
def mpint(b):
    b = b.lstrip(b'\0')
    if b and b[0] & 0x80: b = b'\0' + b
    return s(b)

def pat(n, seed): return bytes((seed * 31 + i * 7) & 0xff for i in range(n))

V_C = b'SSH-2.0-foxtrot_0.0.1'
V_S = b'SSH-2.0-OpenSSH_9.6 test'
I_C = b'\x14' + pat(100, 1)
I_S = b'\x14' + pat(120, 2)
K_S = pat(51, 3)
Q_C = pat(32, 4)
Q_S = pat(32, 5)

def emit(name, v):
    print('static const char *const %s =' % name)
    h = v.hex()
    for i in range(0, max(len(h), 1), 100):
        print('  "%s"%s' % (h[i:i+100], ';' if i + 100 >= len(h) else ''))

print('/* Generated by gen-kex-vectors.py; do not edit.  */')
print()
for n, v in (('v_c', V_C), ('v_s', V_S), ('i_c', I_C), ('i_s', I_S),
             ('k_s', K_S), ('q_c', Q_C), ('q_s', Q_S)):
    emit('vec_' + n, v)

def case(tag, hashf, k_raw, as_string):
    k_enc = s(k_raw) if as_string else mpint(k_raw)
    h = hashf(s(V_C) + s(V_S) + s(I_C) + s(I_S) + s(K_S) + s(Q_C) + s(Q_S) + k_enc).digest()
    emit('vec_%s_k' % tag, k_raw)
    emit('vec_%s_h' % tag, h)
    sid = hashf(b'session id ' + tag.encode()).digest()
    emit('vec_%s_sid' % tag, sid)
    for letter in 'ABCDEF':
        out = b''
        out = hashf(k_enc + h + letter.encode() + sid).digest()
        while len(out) < 80:
            out += hashf(k_enc + h + out).digest()
        emit('vec_%s_key%s' % (tag, letter), out[:80])

case('sha256_mpint', hashlib.sha256, bytes([0x9a]) + pat(31, 6), False)    # needs a sign byte
case('sha256_mpint0', hashlib.sha256, b'\0\0' + pat(30, 7), False)         # leading zeros dropped
case('sha384_mpint', hashlib.sha384, pat(48, 8), False)
case('sha512_string', hashlib.sha512, pat(64, 9), True)
case('sha256_string', hashlib.sha256, pat(32, 10), True)
